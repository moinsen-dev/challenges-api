/**
 * Compiles the WebAssembly fixtures the verification tests use.
 *
 * It runs in Node rather than in the test, because the Workers runtime refuses
 * to compile WebAssembly at runtime — and wabt is itself a WebAssembly module,
 * so it cannot run there either. The output is committed, so the tests stay
 * hermetic and readable.
 *
 *   node scripts/build-test-wasm.mjs
 */
import { writeFileSync } from 'node:fs'
import wabtFactory from 'wabt'

const MODULES = {
  /** Folds a trace into a score, the way a deterministic game core would. */
  scorer: `(module
  (memory (export "memory") 2)
  (func (export "verify") (param $ptr i32) (param $len i32) (result i64)
    (local $i i32) (local $score i64)
    (local.set $i (i32.const 0))
    (local.set $score (i64.const 0))
    (block $done
      (loop $next
        (br_if $done (i32.ge_u (local.get $i) (local.get $len)))
        (local.set $score
          (i64.add
            (i64.mul (local.get $score) (i64.const 31))
            (i64.extend_i32_u (i32.load8_u (i32.add (local.get $ptr) (local.get $i))))))
        (local.set $i (i32.add (local.get $i) (i32.const 1)))
        (br $next)))
    (local.get $score)))`,

  /** Never returns, to prove the sandbox timeout is real. */
  endless: `(module
  (memory (export "memory") 1)
  (func (export "verify") (param i32 i32) (result i64)
    (loop $forever (br $forever))
    (i64.const 0)))`,

  /** Reaches outside itself — refused before it is ever run. */
  importer: `(module
  (import "env" "now" (func $now (result i64)))
  (memory (export "memory") 1)
  (func (export "verify") (param i32 i32) (result i64) (call $now)))`,

  /** Keeps its memory to itself, so a trace cannot be handed in. */
  private: `(module
  (memory 1)
  (func (export "verify") (param i32 i32) (result i64) (i64.const 1)))`,

  /** Traps immediately, the way a module rejecting a trace would. */
  refuses: `(module
  (memory (export "memory") 1)
  (func (export "verify") (param i32 i32) (result i64) (unreachable)))`,
}

const wabt = await wabtFactory()
const out = ['// Generated by scripts/build-test-wasm.mjs — do not edit by hand.', '']

for (const [name, wat] of Object.entries(MODULES)) {
  const parsed = wabt.parseWat(`${name}.wat`, wat)
  const { buffer } = parsed.toBinary({})
  parsed.destroy()
  const base64 = Buffer.from(buffer).toString('base64')
  out.push(`/** ${wat.split('\n')[0]} */`)
  out.push(`export const ${name} = '${base64}'`)
  out.push('')
  console.log(`${name}: ${buffer.length} bytes`)
}

out.push('export const bytes = (base64: string) =>')
out.push('  Uint8Array.from(atob(base64), (ch) => ch.charCodeAt(0))')
out.push('')
writeFileSync(new URL('../tests/fixtures/wasm.ts', import.meta.url), out.join('\n'))
